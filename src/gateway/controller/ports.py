class CancellationToken:
    """Request-scoped signal; durable cancellation belongs to PolicyStore."""
    def __init__(self):
        self._event = asyncio.Event()

    def cancel(self) -> None:
        self._event.set()

    def is_cancelled(self) -> bool:
        return self._event.is_set()

    async def wait_cancelled(self) -> None:
        await self._event.wait()


class PendingGeneration(Protocol):
    def result(self) -> Awaitable[ProviderResult]: ...
    def cancel(self) -> None: ...


class ProviderAdapter(Protocol):
    def capability_profile(self) -> CapabilityProfile: ...
    def serialize(self, request: GatewayRequest) -> ProviderEnvelope: ...
    def begin_generate(self, envelope: ProviderEnvelope, *, ticket: DispatchTicket,
                       deadline: datetime, cancel_token: CancellationToken) -> PendingGeneration: ...


class QuotePort(Protocol):
    """Trusted ACCOUNT bootstrap; hashes alone cannot create price or bound proof.

    No controller fallback implements these methods. Registration/quote source and
    its as-built owner must be accepted by INT before a joined source exit.
    """
    def reserve_for(self, envelope: ProviderEnvelope) -> Decimal: ...
    def register_envelope(self, envelope: ProviderEnvelope) -> str: ...
    def price_usage(self, *, envelope: ProviderEnvelope, usage: ProviderUsage) -> Decimal | None: ...


class LedgerPort(Protocol):
    authority: BudgetAuthority
    # settle MUST retain credible conflicting evidence via the approved ACCOUNT
    # gate using actual committed K/U before returning/raising settlement_conflict.
    # JOURNEY stages receipt first and additionally halts; it cannot infer U.
    def fund_plan(self, permit: OperationPermit) -> FundingReceipt: ...
    def begin_attempt(self, *, operation_id: str, child_id: str, permit_sha256: str) -> DispatchTicket: ...
    def settle(self, receipt: AttemptReceipt) -> SettlementReceipt: ...
    def mark_unknown(self, *, operation_id: str, child_id: str,
                     attempt_id: str, reason: UnknownReason) -> SettlementReceipt: ...
    def close_unstarted(self, proof: UnstartedProof) -> ChildClosureReceipt: ...
    def totals(self, *, authority_id: str) -> AccountingTotals: ...
    def recover(self, evidence: RecoveryEvidence) -> RecoveryReport: ...
    def operation_state(self, operation_id: str) -> LedgerOperationSnapshot | None: ...
    def recovery_candidates(self, authority_id: str, *, cursor: str | None,
                            limit: int) -> LedgerRecoveryPage: ...
    def committed_join(self, *, operation_id: str) -> LedgerJoin | None: ...


class PolicyPort(Protocol):
    def close_unstarted_operation(self, operation_id: str, *, now: datetime) -> OperationSnapshot: ...
    def assert_retry_stage_ready(self, operation_id: str, child_id: str, *, now: datetime) -> None: ...
    def get_permit(self, operation_id: str) -> OperationPermit | None: ...
    def operation_snapshot(self, operation_id: str) -> OperationSnapshot | None: ...
    def routing_snapshot(self, caller: CallerContext, route_alias: str, *, now: datetime) -> RoutingSnapshot: ...
    def lookup_operation(self, caller: CallerContext, key_digest: str) -> OperationSnapshot | None: ...
    def permit_operation(self, request: GatewayRequest, plan: PermitPlan, *, key_digest: str,
                          expected_generation: int, context: EligibilityContext) -> PermitDecision: ...
    def transition_permit(self, operation_id: str, *, expected_state: PermitState,
                          target_state: PermitState, join: LedgerJoin | None) -> OperationPermit: ...
    def assert_dispatch_allowed(self, operation_id: str, join: LedgerJoin,
                                 *, context: EligibilityContext) -> None: ...
    def stage_result(self, operation_id: str, encrypted: EncryptedResult,
                     receipt: AttemptReceipt, *, now: datetime) -> StagedResult: ...
    def mark_terminal(self, operation_id: str, settlement: SettlementReceipt,
                      *, now: datetime, result_expires_utc: datetime | None) -> OperationSnapshot: ...
    def cancel_operation(self, caller: CallerContext, operation_id: str, *, now: datetime) -> OperationSnapshot: ...
    def abandon_unfunded(self, operation_id: str, *, now: datetime) -> bool: ...
    def recovery_candidates(self, authority_id: str, *, cursor: str | None = None,
                            limit: int) -> PolicyRecoveryPage: ...
    def purge_expired_results(self, authority_id: str, *, now: datetime, limit: int) -> int: ...
    def append_incident(self, evidence: IncidentEvidence) -> IncidentRecord: ...
    def halt(self, *, reason_code: str, evidence_sha256: str): ...
